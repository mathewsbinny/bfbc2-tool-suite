ID = re.compile(r'^[a-z0-9][a-z0-9.+-]*$')
DATE = re.compile(r'^\d{4}-\d{2}-\d{2}$')
SEMVER = re.compile(r'^\d+\.\d+\.\d+$')

# canonical key order of a task; '' / [] values are left out of the file
TASK_KEYS = ('id', 'code', 'title', 'lane', 'repos', 'category', 'tags', 'raised', 'started', 'done', 'owner',
             'parent', 'depends', 'merged_into', 'aliases', 'renamed_from', 'version', 'benchmarks', 'kb', 'spec',
             'links', 'score', 'reason', 'body', 'scope', 'source', 'decisions')
LIST_KEYS = ('repos', 'tags', 'depends', 'merged_into', 'aliases', 'renamed_from', 'benchmarks', 'kb', 'spec', 'links')
REQUIRED = ('id', 'code', 'title', 'lane', 'repos', 'category')
DECISION_KEYS = ('date', 'by', 'source', 'choice', 'note')
CATEGORY_KEYS = ('id', 'name', 'definition')
PRIORITY_KEYS = ('rank', 'title', 'ruled', 'by', 'source', 'tasks', 'lanes')

Task = dict[str, Any]


# ---------------------------------------------------------------------------------------------------- TOML writer

def _esc(s: str, multiline: bool = False) -> str:
    out = []
    for ch in s:
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch == '\n' and multiline:
            out.append('\n')
        elif ch == '\n':
            out.append('\\n')
        elif ch == '\t':
            out.append('\\t')
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append(f'\\u{ord(ch):04X}')
        else:
            out.append(ch)
    return ''.join(out)


def _value(v: Any) -> str:
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return repr(v)
    if isinstance(v, str):
        if '\n' in v:
            return '"""\n' + _esc(v, multiline=True) + '"""'
        return '"' + _esc(v) + '"'
    if isinstance(v, list):
        return '[' + ', '.join(_value(x) for x in v) + ']'
    if isinstance(v, dict):
        return '{ ' + ', '.join(f'{k} = {_value(x)}' for k, x in v.items()) + ' }'
    raise TypeError(f'no TOML form for {type(v).__name__}')


def _table(name: str, keys: tuple[str, ...], d: dict[str, Any]) -> list[str]:
    lines = [f'[[{name}]]']
    for k in keys:
        v = d.get(k)
        if v in (None, '', [], {}):
            continue
        if k == 'decisions':
            lines.append('decisions = [')
            for dec in v:
                lines.append('    ' + _value({dk: dec[dk] for dk in DECISION_KEYS if dec.get(dk)}) + ',')
            lines.append(']')
        else:
            lines.append(f'{k} = {_value(v)}')
    return lines


def dump(reg: dict[str, Any]) -> str:
    """The registry in its canonical form: [meta], the categories, the priority groups by rank, the tasks by id;
    fixed key order, empty values left out, no comments (tomllib drops them: put the words in a field)."""
    lines = ['[meta]']
    for k, v in reg['meta'].items():
        lines.append(f'{k} = {_value(v)}')
    for c in reg['category']:
        lines += [''] + _table('category', CATEGORY_KEYS, c)
    for p in sorted(reg['priority'], key=lambda p: p['rank']):
        lines += [''] + _table('priority', PRIORITY_KEYS, p)
    for t in sorted(reg['task'], key=lambda t: t['id']):
        lines += [''] + _table('task', TASK_KEYS, t)
    return '\n'.join(lines) + '\n'


def load(path: str = REGISTRY) -> dict[str, Any]:
    with open(path, 'rb') as f:
        reg = tomllib.load(f)
    reg.setdefault('meta', {})
    reg.setdefault('category', [])
    reg.setdefault('priority', [])
    reg.setdefault('task', [])
    for t in reg['task']:
        for k in LIST_KEYS + ('decisions',):
            t.setdefault(k, [])
        t.setdefault('score', {})
        for k in TASK_KEYS:
            t.setdefault(k, '' if k not in LIST_KEYS + ('decisions',) else [])
    return reg


def write(path: str, text: str) -> None:
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


def read(path: str) -> str:
    with open(path, encoding='utf-8') as f:
        return f.read()


# ------------------------------------------------------------------------------------------------- the evidence

def render_plain(h: str) -> str:
    h = re.sub(r'\[([^\]]*)\]\([^)]*\)', r'\1', h)
    return h.replace('`', '')


def slug(h: str) -> str:
    """GitHub's heading anchor (battlefield-opfor's tools/docs_check.py slugs the same way)."""
    out = []
    for ch in render_plain(h).strip().lower():
        if unicodedata.category(ch)[0] in 'LMN' or ch in '_-':
            out.append(ch)
        elif ch == ' ':
            out.append('-')
    return ''.join(out)


def bench_sections(root: str = SUITE) -> dict[str, tuple[str, str]]:
    """{section name: (file, anchor)} for every `## <name>: ...` heading of BENCHMARKS and its archive; the name is
    the heading's text before the first colon (a round code, sometimes with a qualifier: "E3d (map export)")."""
    out: dict[str, tuple[str, str]] = {}
    for rel in BENCHES:
        path = os.path.join(root, rel)
        if not os.path.isfile(path):
            continue
        seen: dict[str, int] = {}
        fence = False
        for line in read(path).splitlines():
            if line.lstrip().startswith('```'):
                fence = not fence
            if fence:
                continue
            m = re.match(r'^(#{1,6})\s+(.*?)\s*$', line)
            if not m:
                continue
            base = slug(m.group(2))
            n = seen.get(base, 0)
            seen[base] = n + 1
            anchor = base if n == 0 else f'{base}-{n}'
            if len(m.group(1)) == 2 and ':' in m.group(2):
                out.setdefault(m.group(2).split(':', 1)[0].strip(), (rel, anchor))
    return out


def changelog_versions(text: str) -> set[str]:
    return set(re.findall(r'^## \[([^\]]+)\]', text, re.M))


def bfo_root(argv: list[str]) -> str:
    if '--bfo' in argv:
        return os.path.abspath(argv[argv.index('--bfo') + 1])
    return os.environ.get('BFBC2_BFO_ROOT') or os.path.join(os.path.dirname(SUITE), 'battlefield-opfor')


# ---------------------------------------------------------------------------------------------------- the check

def index(reg: dict[str, Any]) -> dict[str, Task]:
    """Every task by its id, code, aliases and old codes (lower case; the first claim wins)."""
    out: dict[str, Task] = {}
    for t in reg['task']:
        out.setdefault(t['id'], t)
    for t in reg['task']:
        out.setdefault(t['code'].lower(), t)
    for key in ('aliases', 'renamed_from'):
        for t in reg['task']:
            for a in t[key]:
                out.setdefault(a.lower(), t)
    return out


def problems(reg: dict[str, Any], text: str, root: str = SUITE, bfo: str | None = None) -> list[str]:
    out: list[str] = []
    if dump(reg) != text:
        out.append('tasks/registry.toml is not in its canonical form (run: python tasks\\build.py --fmt)')
    cats = [c.get('id', '') for c in reg['category']]
    if len(set(cats)) != len(cats):
        out.append('a category id is used twice')
    for c in reg['category']:
        for k in CATEGORY_KEYS:
            if not c.get(k):
                out.append(f'category {c.get("id", "?")}: no {k}')
    ids: dict[str, str] = {}
    names: dict[str, str] = {}
    for t in reg['task']:
        tid = t.get('id', '')
        where = f'task {tid or t.get("code", "?")}'
        for k in REQUIRED:
            if not t.get(k):
                out.append(f'{where}: no {k}')
        for k in t:
            if k not in TASK_KEYS:
                out.append(f'{where}: unknown field {k!r}')
        if tid in ids:
            out.append(f'{where}: duplicate id')
        ids[tid] = tid
        if not ID.match(tid):
            out.append(f'{where}: the id is not lower case letters, digits and . + -')
        for name in [t['code']] + t['aliases']:
            key = name.lower()
            if key in names and names[key] != tid:
                out.append(f'{where}: code or alias {name!r} is also {names[key]}\'s')
            names[key] = tid
        if t['lane'] not in LANES:
            out.append(f'{where}: unknown lane {t["lane"]!r}')
        if t['category'] not in cats:
            out.append(f'{where}: unknown category {t["category"]!r}')
        for r in t['repos']:
            if r not in REPOS:
                out.append(f'{where}: unknown repository {r!r}')
        for k in ('raised', 'started', 'done'):
            if t[k] and not DATE.match(t[k]):
                out.append(f'{where}: {k} {t[k]!r} is not YYYY-MM-DD')
        if t['lane'] == 'done' and not t['done']:
            out.append(f'{where}: done with no done date')
        if t['lane'] != 'done' and t['done']:
            out.append(f'{where}: a done date but lane {t["lane"]}')
        if t['lane'] == 'dropped' and not (t['reason'] or t['merged_into']):
            out.append(f'{where}: dropped with no reason and nothing it was merged into')
        if t['merged_into'] and t['lane'] != 'dropped':
            out.append(f'{where}: merged_into but lane {t["lane"]} (a merged task is dropped)')
        if t['version'] and t['version'] != 'unreleased' and not SEMVER.match(t['version']):
            out.append(f'{where}: version {t["version"]!r} is not X.Y.Z or "unreleased"')
        if t['version'] and t['lane'] != 'done':
            out.append(f'{where}: a version but lane {t["lane"]} (versions are assigned at the merge)')
        sc = t['score']
        if sc and (set(sc) != {'d', 't', 'h'} or not all(isinstance(x, (int, float)) for x in sc.values())):
            out.append(f'{where}: score is not {{ d = <1-5>, t = <1-5>, h = <agent-hours> }}')
        for d in t['decisions']:
            for k in ('date', 'by', 'source', 'choice'):
                if not d.get(k):
                    out.append(f'{where}: a decision with no {k}')
            if d.get('date') and not DATE.match(d['date']):
                out.append(f'{where}: decision date {d["date"]!r} is not YYYY-MM-DD')
    for t in reg['task']:
        where = f'task {t["id"]}'
        for k in ('depends', 'merged_into'):
            for ref in t[k]:
                if ref not in ids:
                    out.append(f'{where}: {k} names {ref!r}, no task has that id')
                elif ref == t['id']:
                    out.append(f'{where}: {k} names itself')
        if t['parent'] and t['parent'] not in ids:
            out.append(f'{where}: parent {t["parent"]!r} is no task id')
    for p in reg['priority']:
        for ref in p.get('tasks', []):
            if ref not in ids:
                out.append(f'priority {p.get("rank")}: names {ref!r}, no task has that id')
        for lane in p.get('lanes', []):
            if lane not in LANES:
                out.append(f'priority {p.get("rank")}: unknown lane {lane!r}')
    sections = bench_sections(root)
    for t in reg['task']:
        for b in t['benchmarks']:
            if b not in sections:
                out.append(f'task {t["id"]}: benchmarks names section {b!r}, which neither BENCHMARKS file has')
    versions = changelog_versions(read(os.path.join(root, 'CHANGELOG.md')))
    for t in reg['task']:
        v = t['version']
        if v and (v if v != 'unreleased' else 'Unreleased') not in versions:
            out.append(f'task {t["id"]}: version {v} has no heading in CHANGELOG.md')
    if bfo and os.path.isdir(bfo):
        for t in reg['task']:
            for k in t['kb']:
                if not os.path.exists(os.path.join(bfo, k.split('#', 1)[0])):
                    out.append(f'task {t["id"]}: kb names {k!r}, missing in {bfo}')
    if os.path.isdir(CHANGES):
        for f in sorted(os.listdir(CHANGES)):
            if f.endswith('.md') and f != 'README.md':
                t = next((t for t in reg['task'] if t['id'] == f[:-3]), None)
                if t is None:
                    out.append(f'tasks/changes/{f}: no task has the id {f[:-3]!r}')
                elif t['lane'] in ('done', 'dropped'):
                    out.append(f'tasks/changes/{f}: task {t["id"]} is {t["lane"]} but its fragment was not merged '
                               '(python tasks\\build.py merge)')
    ps = os.path.join(root, 'python_status.json')
    if os.path.isfile(ps):
        rows = json.loads(read(ps)).get('files', [])
        known = {t['code'] for t in reg['task']}
        for code in sorted({str(r.get('retiring', '')) for r in rows}):
            if code not in known:
                out.append(f'python_status.json: retiring round {code!r} is no task code')
    return out


# ------------------------------------------------------------------------------------------------ the renderers

def cell(s: str) -> str:
    return ' '.join(str(s).split()).replace('|', '\\|')


def clip(s: str, n: int = 170) -> str:
    s = ' '.join(s.split())
    if len(s) <= n:
        return s
    cut = s.rfind(' ', 0, n - 3)
    return s[:cut if cut > 0 else n - 3].rstrip(',;:') + ' ...'


def repos(t: Task) -> str:
    return ', '.join(t['repos'])


def codes(ts: list[Task]) -> str:
    return ', '.join(f'`{t["code"]}`' for t in ts)


def ranks(reg: dict[str, Any]) -> dict[str, tuple[int, int]]:
    """{task id: (its priority group's rank, its place in the group)}; lane selectors place after the listed ids."""
    out: dict[str, tuple[int, int]] = {}
    for p in sorted(reg['priority'], key=lambda p: p['rank']):
        for i, tid in enumerate(p.get('tasks', [])):
            out.setdefault(tid, (p['rank'], i))
        for lane in p.get('lanes', []):
            for t in reg['task']:
                if t['lane'] == lane:
                    out.setdefault(t['id'], (p['rank'], 10_000))
    return out


def by_lane(reg: dict[str, Any], lane: str) -> list[Task]:
    """A lane's tasks: done and dropped newest first; the open lanes in priority order, then by date raised."""
    ts = [t for t in reg['task'] if t['lane'] == lane]
    if lane in ('done', 'dropped'):
        return sorted(ts, key=lambda t: (t['done'] or t['raised'] or '', t['code']), reverse=True)
    rk = ranks(reg)
    return sorted(ts, key=lambda t: (rk.get(t['id'], (99, 0)), t['raised'] or '9999', t['code']))


def on_roadmap(t: Task) -> bool:
    return bool({'suite', 'xenolith', 'all'} & set(t['repos']))


def evidence(t: Task, sections: dict[str, tuple[str, str]], prefix: str = '') -> str:
    """The round's evidence: its BENCHMARKS sections (links when prefix is '', named for another repository)."""
    out = []
    for b in t['benchmarks']:
        rel, anchor = sections.get(b, (BENCHES[0], ''))
        name = os.path.basename(rel).replace('.md', '')
        if prefix:
            out.append(f'`{prefix}{rel}` "{b}"')
        else:
            out.append(f'[{name} "{b}"]({rel}#{anchor})')
    return '; '.join(out)


def after(t: Task, ix: dict[str, Task]) -> str:
    deps = [ix[d] for d in t['depends'] if d in ix]
    open_deps = [d for d in deps if d['lane'] not in ('done', 'dropped')]
    return ', '.join(d['code'] for d in open_deps)


def priority_lines(reg: dict[str, Any]) -> list[str]:
    out = []
    ids = {t['id']: t for t in reg['task']}
    for p in sorted(reg['priority'], key=lambda p: p['rank']):
        members = [ids[i] for i in p.get('tasks', []) if i in ids]
        for lane in p.get('lanes', []):
            members += [t for t in by_lane(reg, lane) if t not in members]
        live = [t for t in members if t['lane'] not in ('done', 'dropped')]
        finished = [t for t in members if t['lane'] == 'done']
        ruled = f'{p.get("by", "the user")}, {p["ruled"]}' + (f'; {p["source"]}' if p.get('source') else '')
        line = f'{p["rank"]}. **{p["title"]}** ({ruled}): ' + (codes(live) if live else 'nothing open')
        if finished:
            line += f' (done: {len(finished)})'
        out.append(line + '.')
    return out


def roadmap(reg: dict[str, Any], version: str, root: str = SUITE) -> str:
    sections = bench_sections(root)
    ix = {t['id']: t for t in reg['task']}
    n_open = sum(t['lane'] in OPEN for t in reg['task'])
    o = [BEGIN, '',
         f'{len(reg["task"])} tasks in the registry, {n_open} open; the suite\'s version {version} (`VERSION`). '
         'Every task with its full scope, decisions and links: `tasks/registry.toml` '
         '(`python tasks\\build.py show <code>`); every repository\'s tasks on one page: battlefield-opfor\'s '
         '`docs/tasks/TASKS.md`.', '',
         '## Priority order', '',
         "The groups in the order the user ranked them, each with the ruling it comes from; a line lists the group's "
         'open tasks in order (the queues below follow it).', '']
    o += priority_lines(reg)
    o += ['', '## In progress', '', '| Round | Branch | Repositories | What | Since |', '|---|---|---|---|---|']
    for t in by_lane(reg, 'run'):
        o.append(f'| {t["code"]} | {cell(t["owner"])} | {repos(t)} | {cell(t["title"])} | '
                 f'{t["started"] or t["raised"]} |')
    o += ['', '## Ready to merge', '', '| Round | Branch | Repositories | What | Merge after |', '|---|---|---|---|---|']
    for t in by_lane(reg, 'merge'):
        o.append(f'| {t["code"]} | {cell(t["owner"])} | {repos(t)} | {cell(t["title"])} | {after(t, ix)} |')
    for lane in ('next', 'later'):
        o += ['', f'## {LANES[lane]}', '', '| Task | Repositories | What | After |', '|---|---|---|---|']
        for t in by_lane(reg, lane):
            if on_roadmap(t):
                o.append(f'| {t["code"]} | {repos(t)} | {cell(t["title"])}'
                         + (f': {cell(clip(t["body"]))}' if t['body'] else '') + f' | {after(t, ix)} |')
    bfo_only = [t for t in reg['task'] if t['lane'] in OPEN and not on_roadmap(t)]
    o += ['', "## battlefield-opfor's and Project OPFOR's own queue", '',
          f'{len(bfo_only)} open tasks touch neither the suite nor xenolith; they are in battlefield-opfor\'s '
          '`docs/tasks/TASKS.md`: ' + codes(sorted(bfo_only, key=lambda t: t['code'])) + '.']
    o += ['', '## On hold', '', '| Task | Repositories | What |', '|---|---|---|']
    for t in by_lane(reg, 'hold'):
        if on_roadmap(t):
            o.append(f'| {t["code"]} | {repos(t)} | {cell(t["title"])}'
                     + (f': {cell(clip(t["body"]))}' if t['body'] else '') + ' |')
    o += ['', '## Done', '',
          'One line per round, most recent first: the date it was merged, the version that released it, its evidence. '
          f'The rows this section had until 2026-11-28 (each round\'s result in a sentence or a paragraph) are in '
          f'[{ARCHIVE}]({ARCHIVE}); the commit messages and CHANGELOG.md have the rest.', '']
    for t in by_lane(reg, 'done'):
        if not on_roadmap(t):
            continue
        meta = t['done'] + (f', {t["version"]}' if t['version'] else '')
        ev = evidence(t, sections)
        o.append(f'- **{t["code"]}** ({meta}): {cell(t["title"])}' + (f'. Evidence: {ev}' if ev else ''))
    o += ['', '## Dropped and merged', '']
    for t in by_lane(reg, 'dropped'):
        if on_roadmap(t):
            o.append(f'- **{t["code"]}**: {cell(t["title"])} - {dropped_why(t, ix)}')
    o += ['', END]
    return '\n'.join(o) + '\n'


def dropped_why(t: Task, ix: dict[str, Task]) -> str:
    if t['merged_into']:
        why = 'merged into ' + ', '.join(ix[m]['code'] if m in ix else m for m in t['merged_into'])
        return why + (f' ({cell(t["reason"])})' if t['reason'] else '')
    return 'dropped: ' + cell(t['reason'])


def splice(text: str, body: str) -> str:
    a, b = text.find(BEGIN), text.find(END)
    if a < 0 or b < a:
        raise SystemExit('ROADMAP.md has no BEGIN / END GENERATED markers')
    return text[:a] + body + text[b + len(END) + 1:]


def tasks_md(reg: dict[str, Any], version: str, root: str = SUITE) -> str:
    sections = bench_sections(root)
    ix = {t['id']: t for t in reg['task']}
    o = ['# Tasks', '',
         '**Generated** by the suite\'s `tasks/build.py` from `<suite>/tasks/registry.toml`, the one task registry of '
         'every repository (round TK0, 2026-11-28): do not edit this page, edit the registry and run '
         '`python <suite>\\tasks\\build.py`. The suite\'s `ROADMAP.md` is written from the same registry.', '',
         f'{len(reg["task"])} tasks; the suite at version {version}. Lanes: ' + ', '.join(
             f'{LANES[l]} {sum(t["lane"] == l for t in reg["task"])}' for l in LANES) + '.', '',
         '- **Owner** is the round\'s branch (its worktree under `<rounds>/<round>/`).',
         '- **After** lists the open tasks it waits for.',
         '- A task\'s full scope, its decisions (who ruled, when, where) and its links: '
         '`python <suite>\\tasks\\build.py show <code>`.', '']
    for lane in OPEN:
        ts = by_lane(reg, lane)
        o += [f'## {LANES[lane]} ({len(ts)})', '', '| Task | Repositories | Category | What | Owner / after | Links |',
              '|---|---|---|---|---|---|']
        for t in ts:
            what = cell(t['title']) + (f': {cell(clip(t["body"], 220))}' if t['body'] else '')
            own = ' / '.join(x for x in (cell(t['owner']), after(t, ix)) if x)
            o.append(f'| {t["code"]} | {repos(t)} | {t["category"]} | {what} | {own} | {kb_links(t, sections)} |')
        o.append('')
    done = by_lane(reg, 'done')
    o += [f'## {LANES["done"]} ({len(done)})', '', 'Most recent first.', '',
          '| Task | Done | Version | Repositories | What | Evidence |', '|---|---|---|---|---|---|']
    for t in done:
        o.append(f'| {t["code"]} | {t["done"]} | {t["version"]} | {repos(t)} | {cell(t["title"])} | '
                 f'{kb_links(t, sections)} |')
    dropped = by_lane(reg, 'dropped')
    o += ['', f'## {LANES["dropped"]} ({len(dropped)})', '', '| Task | Repositories | What | Why |', '|---|---|---|---|']
    for t in dropped:
        o.append(f'| {t["code"]} | {repos(t)} | {cell(t["title"])} | {dropped_why(t, ix)} |')
    return '\n'.join(o) + '\n'


def kb_links(t: Task, sections: dict[str, tuple[str, str]]) -> str:
    out = []
    for k in t['kb']:
        path = k[len('docs/'):] if k.startswith('docs/') else '../../' + k
        out.append(f'[{os.path.basename(k.split("#")[0])}](../{path})')
    ev = evidence(t, sections, prefix='<suite>/')
    return '; '.join(out + ([ev] if ev else []))


def board(reg: dict[str, Any]) -> str:
    data = {
        'generator': 'tasks/build.py', 'registry': 'tasks/registry.toml',
        'lanes': [{'id': k, 'name': v} for k, v in LANES.items()],
        'cats': [{'id': c['id'], 'name': c['name']} for c in reg['category']],
        'tasks': [{'id': t['id'], 'lane': t['lane'], 'code': t['code'], 'title': t['title'],
                   'repo': ' · '.join(t['repos']), 'category': t['category'], 'tags': t['tags'],
                   'note': t['body'], 'date': t['done'] or t['started'] or t['raised'], 'version': t['version'],
                   'depends': t['depends'], 'decided': bool(t['decisions']), 'onRoadmap': on_roadmap(t),
                   'score': t['score'] or None,
                   'contention': False}
                  for t in sorted(reg['task'], key=lambda t: t['id'])],
    }
    return json.dumps(data, ensure_ascii=False, indent=0, sort_keys=True) + '\n'


# ------------------------------------------------------------------------------------- merge-time CHANGELOG steps

def section_span(text: str, heading: str) -> tuple[int, int]:
    a = text.find(heading)
    if a < 0:
        raise SystemExit(f'CHANGELOG.md has no {heading!r}')
    m = re.compile(r'^## \[', re.M).search(text, a + len(heading))
    return a + len(heading), (m.start() if m else len(text))


def consolidate(body: str) -> str:
    """One Added / Changed / Fixed / Removed list each, the lead paragraphs first (rounds' fragments are appended to
    Unreleased one after another, so a heading can repeat until the version is cut)."""
    lead: list[str] = []
    parts: dict[str, list[str]] = {}
    cur: list[str] = lead
    for line in body.strip('\n').splitlines():
        if line.startswith('### '):
            cur = parts.setdefault(line[4:].strip(), [])
        else:
            cur.append(line)
    order = [h for h in ('Added', 'Changed', 'Fixed', 'Removed') if h in parts] + \
        [h for h in parts if h not in ('Added', 'Changed', 'Fixed', 'Removed')]
    out = '\n'.join(lead).strip('\n')
    for h in order:
        items = '\n'.join(parts[h]).strip('\n')
        out += f'\n\n### {h}\n\n{items}'
    return out.strip('\n')


def cut(reg: dict[str, Any], version: str, date: str) -> None:
    text = read(CHANGELOG)
    a, b = section_span(text, '## [Unreleased]')
    body = consolidate(text[a:b])
    if not body:
        raise SystemExit('CHANGELOG.md: Unreleased is empty, nothing to release')
    write(CHANGELOG, text[:a] + f'\n\n## [{version}] - {date}\n\n{body}\n\n' + text[b:])
    write(VERSION, version + '\n')
    for t in reg['task']:
        if t['version'] == 'unreleased':
            t['version'] = version
    print(f'CHANGELOG.md: Unreleased released as {version}; VERSION {version}')


def next_minor(v: str) -> str:
    major, minor, _ = (int(x) for x in v.split('.'))
    return f'{major}.{minor + 1}.0'


def merge(reg: dict[str, Any], code: str, date: str, version: str = '') -> None:
    t = index(reg).get(code.lower())
    if t is None:
        raise SystemExit(f'no task {code!r}')
    t['lane'] = 'done'
    t['done'] = date
    t['started'] = t['started'] or t['raised'] or date
    frag = os.path.join(CHANGES, t['id'] + '.md')
    if os.path.isfile(frag):
        body = read(frag).strip('\n')
        text = read(CHANGELOG)
        a, b = section_span(text, '## [Unreleased]')
        old = text[a:b].strip('\n')
        new = (old + '\n\n' if old else '') + body
        write(CHANGELOG, text[:a] + '\n\n' + new + '\n\n' + text[b:])
        os.remove(frag)
        t['version'] = 'unreleased'
        print(f'CHANGELOG.md: {os.path.basename(frag)} added to Unreleased')
        if re.search(r'^### Removed', body, re.M):
            cut(reg, next_minor(read(VERSION).strip()), date)
    elif version:
        # a branch that wrote CHANGELOG / VERSION the old way (before TK0): its version, and the Unreleased
        # entries its version heading took in
        for u in reg['task']:
            if u['version'] == 'unreleased':
                u['version'] = version
        t['version'] = version
    else:
        print(f'{t["code"]}: no tasks/changes/{t["id"]}.md, so no CHANGELOG entry (nothing a user notices)')
    print(f'{t["code"]}: done {date}' + (f', version {t["version"]}' if t['version'] else ''))


# ------------------------------------------------------------------------------------------------------ the CLI

def outputs(reg: dict[str, Any], bfo: str) -> list[tuple[str, str, bool]]:
    """(path, text, is_bfo) for every generated file."""
    version = read(VERSION).strip()
    out = [(ROADMAP, splice(read(ROADMAP), roadmap(reg, version)), False), (BOARD, board(reg), False)]
    if os.path.isdir(os.path.join(bfo, 'docs', 'tasks')):
        out.append((os.path.join(bfo, TASKS_MD), tasks_md(reg, version), True))
    return out


def show(t: Task) -> str:
    lines = []
    for k in TASK_KEYS:
        v = t.get(k)
        if v in ('', [], None):
            continue
        if k == 'decisions':
            for d in v:
                lines.append('decision: ' + '; '.join(f'{dk} {d[dk]}' for dk in DECISION_KEYS if d.get(dk)))
        elif isinstance(v, list):
            lines.append(f'{k}: {", ".join(v)}')
        else:
            lines.append(f'{k}: {v}')
    return '\n'.join(lines)


def main(argv: list[str]) -> int:
    text = read(REGISTRY)
    reg = load()
    bfo = bfo_root(argv)
    date = argv[argv.index('--date') + 1] if '--date' in argv else datetime.date.today().isoformat()
    args = [a for i, a in enumerate(argv) if not a.startswith('--') and (i == 0 or argv[i - 1] not in
                                                                          ('--bfo', '--date', '--version'))]
    if '--fmt' in argv:
        write(REGISTRY, dump(reg))
        print('tasks/registry.toml: canonical form written')
        return 0
    if args and args[0] == 'show':
        t = index(reg).get(args[1].lower()) if len(args) > 1 else None
        if t is None:
            print(f'no task {args[1:]!r}')
            return 1
        print(show(t))
        return 0
    if args and args[0] in ('merge', 'cut'):
        if args[0] == 'merge':
            if len(args) < 2:
                print('usage: build.py merge <code> [--date YYYY-MM-DD]')
                return 2
            merge(reg, args[1], date, argv[argv.index('--version') + 1] if '--version' in argv else '')
        else:
            version = argv[argv.index('--version') + 1] if '--version' in argv else next_minor(read(VERSION).strip())
            cut(reg, version, date)
        write(REGISTRY, dump(reg))
        text = dump(reg)
    elif args:
        print(f'unknown command {args[0]!r} (see the docstring: python tasks\\build.py --help)')
        return 2
    if '--help' in argv or '-h' in argv:
        print(__doc__)
        return 0
    found = problems(reg, text, bfo=bfo)
    if '--check' in argv:
        stale: list[str] = []
        warn: list[str] = []
        for path, new, is_bfo in outputs(reg, bfo):
            if not os.path.isfile(path) or read(path) != new:
                (warn if is_bfo and '--strict-bfo' not in argv else stale).append(path)
        for w in warn:
            print(f'note: {w} is behind the registry (run python tasks\\build.py there, or --strict-bfo to fail)')
        found += [f'{p}: stale (run: python tasks\\build.py)' for p in stale]
        for p in found:
            print(f'FAIL {p}')
        if not found:
            print(f'ok   tasks: {len(reg["task"])} tasks valid, the generated files current')
        return 1 if found else 0
    if found:
        for p in found:
            print(f'FAIL {p}')
        return 1
    for path, new, _ in outputs(reg, bfo):
        if not os.path.isfile(path) or read(path) != new:
            write(path, new)
            print(f'wrote {path}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
