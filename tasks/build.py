PYSTATUS = os.path.join(SUITE, 'python_status.json')
BENCHES = ('rust/BENCHMARKS.md', 'rust/BENCHMARKS_ARCHIVE_1.md')
ARCHIVE = 'docs/archive/ROADMAP_DONE_2026-11-28.md'
TASKS_MD = os.path.join('docs', 'tasks', 'TASKS.md')

BEGIN = '<!-- BEGIN GENERATED by tasks/build.py from tasks/registry.toml: edit the registry, not this part -->'
END = '<!-- END GENERATED -->'

LANES = {
    'run': 'In progress',
    'merge': 'Ready to merge',
    'next': 'Queued next',
    'bfo': "Queued: battlefield-opfor's phase",
    'later': 'Queued later',
    'hold': 'On hold',
    'done': 'Done',
    'dropped': 'Dropped or merged',
}
OPEN = ('run', 'merge', 'next', 'bfo', 'later', 'hold')
