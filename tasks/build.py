r"""The task registry's generator and check (round TK0): tasks/registry.toml is the one source of truth for every
task of the project (the suite, battlefield-opfor, xenolith, Project OPFOR BFBC2 and the retired BF1943 projects);
the trackers people read are written from it.

    python tasks\build.py                 write every generated file (below)
    python tasks\build.py --check         fail if the registry is invalid or a generated file is stale (quick tier)
    python tasks\build.py --fmt           rewrite tasks\registry.toml in its canonical form (after a hand edit)
    python tasks\build.py show <code>     print one task (its code, an alias or an old code)
    python tasks\build.py merge <code> [--date D] [--version V]   at a round's merge: Done, its CHANGELOG fragment,
                                          its version (--version V: a branch that wrote its version the old way)
    python tasks\build.py cut [--version X.Y.Z] [--date D]   release CHANGELOG's Unreleased as a version

Options: --bfo <path> names the battlefield-opfor checkout (default: BFBC2_BFO_ROOT, else battlefield-opfor beside
the suite); --strict-bfo makes a stale battlefield-opfor TASKS.md fail --check (without it, a warning: the suite's
quick tier does not fail on another repository's state).

Generated files:
- ROADMAP.md, between its BEGIN / END GENERATED markers: the priority order, in progress, ready to merge, the
  queues, on hold, Done (one line per round with its version and evidence) and the dropped / merged tasks;
- tasks\board.json: the task board's data (the board page's generator reads it);
- battlefield-opfor's docs\tasks\TASKS.md: every task by status, when that checkout is found.

The registry's schema, the lanes and the rules (ids, merges, versions, conflicts) are tasks\README.md's.
Standard library only.
"""
