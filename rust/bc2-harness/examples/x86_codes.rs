//! The proof keys of every decode at every byte offset of an exe's code (the encodings the capstone parity run
//! proved), written as `src/x86_verified.rs`'s tables.
//!
//!   cargo run --release -p bc2-harness --example x86_codes -- <BFBC2Game.exe> <x86_verified.rs>

#![allow(
    clippy::print_stdout,
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::indexing_slicing,
    clippy::many_single_char_names,
    clippy::doc_markdown,
    missing_docs
)]

use std::collections::BTreeSet;
use std::fmt::Write as _;

use bc2_harness::pe::Image;
use bc2_harness::x86::Disassembler;

fn table(s: &mut String, name: &str, doc: &str, keys: &BTreeSet<u32>) {
    let _ = writeln!(s, "/// {doc}");
    let _ = writeln!(s, "#[rustfmt::skip]");
    let _ = writeln!(s, "pub static {name}: [u32; {}] = [", keys.len());
    let v: Vec<u32> = keys.iter().copied().collect();
    for chunk in v.chunks(10) {
        let line: Vec<String> = chunk
            .iter()
            .map(|k| format!("0x{:04X}_{:04X}", k >> 16, k & 0xFFFF))
            .collect();
        let _ = writeln!(s, "    {},", line.join(", "));
    }
    s.push_str("];\n");
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let file = std::fs::read(&args[1]).expect("read the exe");
    let img = Image::parse(&file).expect("map the exe");
    let d = Disassembler::new();
    let mut insns = BTreeSet::new();
    let mut nones = BTreeSet::new();
    let mut starts = 0usize;
    for (lo, hi) in img.code_ranges() {
        for a in lo..hi {
            let o = (a - img.base) as usize;
            let end = (o + 16).min(img.data.len());
            match d.key_of(&img.data[o..end], a) {
                Ok(k) => {
                    insns.insert(k);
                }
                Err(Some(k)) => {
                    nones.insert(k);
                }
                Err(None) => {}
            }
            starts += 1;
        }
    }
    let mut s = String::new();
    let _ = write!(
        s,
        "//! The proof tables of `x86`: every decode at every byte offset of BFBC2Game.exe's code (build 795745), each of\n\
         //! its {starts} starts identical to capstone 5.0's. Generated by\n\
         //! `cargo run --release -p bc2-harness --example x86_codes -- <BFBC2Game.exe> <this file>`; a key outside them\n\
         //! is decoded by capstone (the Python reference).\n\n"
    );
    table(
        &mut s,
        "VERIFIED",
        "The instructions proved (`x86::insn_key`: iced code << 8 | prefix bits), ascending.",
        &insns,
    );
    s.push('\n');
    table(
        &mut s,
        "VERIFIED_NONE",
        "The undecodable byte patterns proved (`x86::invalid_key`), ascending: capstone decodes nothing there either.",
        &nones,
    );
    std::fs::write(&args[2], s).expect("write the tables");
    println!(
        "{} instruction keys, {} undecodable keys, {starts} starts",
        insns.len(),
        nones.len()
    );
}
